"""
preprocess.py
─────────────
Loads the ML-ready CSV exported from Lobato Tours and validates/cleans it.
All encoding is already done by the API (dichotomous columns), so this
module handles:
  • Loading & type coercion
  • Missing-value imputation
  • Feature/target split
  • Train/test split
  • Optional: feature scaling for linear models

Usage
─────
    from preprocess import load_and_prepare

    X_train, X_test, y_train, y_test, feature_names = load_and_prepare("data.csv")
"""

import sys
import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler


# ── Columns that are already binary (0/1) or purely numeric ──────────────────
# These were generated by the /api/cotizaciones/ml-export endpoint.
# No further encoding is needed — the API already one-hot-encoded all strings.

# Columns to DROP before training (identifiers, not features):
DROP_COLS = ["cotizacion_id"]

# Target column:
TARGET = "sold"


def load_csv(path: str) -> pd.DataFrame:
    """Read the ML-export CSV and coerce all columns to numeric."""
    try:
        df = pd.read_csv(path, encoding="utf-8-sig")   # utf-8-sig strips the BOM
    except FileNotFoundError:
        sys.exit(f"[ERROR] File not found: {path}")

    print(f"  Loaded {len(df):,} rows × {len(df.columns)} columns from '{path}'")
    return df


def clean(df: pd.DataFrame) -> pd.DataFrame:
    """Coerce types, fill missing values, remove unusable rows."""
    # Force everything to numeric (non-parseable → NaN)
    for col in df.columns:
        df[col] = pd.to_numeric(df[col], errors="coerce")

    # Drop rows where target is missing
    before = len(df)
    df = df.dropna(subset=[TARGET])
    dropped = before - len(df)
    if dropped:
        print(f"  Dropped {dropped} rows with missing '{TARGET}'.")

    # Fill remaining NaNs with 0 (all columns are counts/costs/binary flags)
    df = df.fillna(0)

    # Ensure binary columns are truly 0/1 integers
    binary_cols = [c for c in df.columns if c.startswith("has_") or c.startswith("airline_")
                   or c.startswith("cruise_") or c.startswith("insurance_")
                   or c.startswith("seguro_tipo") or c.startswith("traslado_tipo")
                   or c in ("finished", "sold", "uses_dollar")]
    for col in binary_cols:
        if col in df.columns:
            df[col] = df[col].clip(0, 1).astype(int)

    print(f"  Clean shape: {df.shape}")
    return df


def describe(df: pd.DataFrame) -> None:
    """Print a quick dataset summary."""
    print("\n── Dataset summary ──────────────────────────────────────────────────────")
    print(f"  Total quotes  : {len(df):,}")
    sold = df[TARGET].sum()
    print(f"  Sold (1)      : {int(sold):,}  ({100*sold/len(df):.1f}%)")
    print(f"  Not sold (0)  : {int(len(df)-sold):,}  ({100*(1-sold/len(df)):.1f}%)")
    print(f"  Features      : {len(df.columns) - 1}")
    print()

    # Services penetration
    svc_cols = [c for c in df.columns if c.startswith("has_")]
    pen = df[svc_cols].mean().sort_values(ascending=False)
    print("  Service penetration (% of quotes):")
    for col, val in pen.items():
        bar = "█" * int(val * 20)
        print(f"    {col:<28} {100*val:5.1f}%  {bar}")
    print()


def split(
    df: pd.DataFrame,
    test_size: float = 0.2,
    random_state: int = 42,
    scale: bool = False,
) -> tuple:
    """
    Returns (X_train, X_test, y_train, y_test, feature_names).

    If scale=True the numerical (non-binary) columns are StandardScaler-normalised.
    Binary columns are never scaled.
    """
    feature_cols = [c for c in df.columns if c not in DROP_COLS + [TARGET]]
    X = df[feature_cols].copy()
    y = df[TARGET].astype(int)

    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=test_size, random_state=random_state, stratify=y
    )

    if scale:
        binary_mask = X_train.columns.str.startswith((
            "has_", "airline_", "cruise_", "insurance_",
            "seguro_tipo", "traslado_tipo",
        )) | X_train.columns.isin(["finished", "uses_dollar"])

        numeric_cols = X_train.columns[~binary_mask].tolist()
        scaler = StandardScaler()
        X_train[numeric_cols] = scaler.fit_transform(X_train[numeric_cols])
        X_test[numeric_cols]  = scaler.transform(X_test[numeric_cols])

    print(f"  Train: {len(X_train):,} rows  |  Test: {len(X_test):,} rows")
    return X_train, X_test, y_train, y_test, feature_cols


def load_and_prepare(
    path: str,
    test_size: float = 0.2,
    random_state: int = 42,
    scale: bool = False,
    verbose: bool = True,
) -> tuple:
    """Full pipeline: load → clean → describe → split."""
    df = load_csv(path)
    df = clean(df)
    if verbose:
        describe(df)
    return split(df, test_size=test_size, random_state=random_state, scale=scale)
